export const TOOLS: Tool[] = ROWS.map(([id, name, category, domain]) => ({
  id,
  name,
  category,
  url: `https://${domain}`,
}))

export const TOOLS_BY_ID: Record<string, Tool> = Object.fromEntries(TOOLS.map((t) => [t.id, t]))

export function initials(name: string): string {
  const parts = name
    .replace(/[^A-Za-z0-9 ]/g, ' ')
    .split(/\s+/)
    .filter(Boolean)
  const s = parts.length > 1 ? parts[0][0] + parts[1][0] : (parts[0] ?? '?').slice(0, 2)
  return s.toUpperCase()
}

export function searchTools(query: string, category?: ToolCategoryId): Tool[] {
  const q = query.trim().toLowerCase()
  return TOOLS.filter(
    (t) => (!category || t.category === category) && (!q || t.name.toLowerCase().includes(q)),
  )
}
